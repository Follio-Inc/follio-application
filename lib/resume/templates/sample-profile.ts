/** Minimal section rows so CleanResumeView actually paints body content. */
export function buildResumePreviewSections(profileId: string): PublicProfile['sections'] {
  const configs: { type: SectionType; title: string }[] = [
    { type: 'BASIC_INFO', title: 'Header' },
    { type: 'PHOTOS', title: 'Photos' },
    { type: 'SUMMARY', title: 'Summary' },
    { type: 'EXPERIENCE', title: 'Experience' },
    { type: 'EDUCATION', title: 'Education' },
    { type: 'SKILLS', title: 'Skills' },
    { type: 'PROJECTS', title: 'Projects' },
    { type: 'LINKS', title: 'Links' },
    { type: 'AWARDS', title: 'Awards' },
    { type: 'CERTIFICATIONS', title: 'Certifications' },
  ];

  return configs.map((config, index) => ({
    id: `${profileId}-section-${config.type.toLowerCase()}`,
    profileId,
    type: config.type,
    customName: null,
    title: config.title,
    sortOrder: index,
    isVisible: true,
    customContent: null,
    contentType: 'STRUCTURED' as const,
    createdAt: now,
    updatedAt: now,
  })) as PublicProfile['sections'];
}

